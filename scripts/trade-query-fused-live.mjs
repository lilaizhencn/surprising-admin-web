import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const fixturePath = process.env.TRADE_QUERY_LIVE_FIXTURE;
assert(fixturePath?.startsWith("/tmp/surprising-option-fused-"));
const deadline = Date.now() + 180_000;
while (!fs.existsSync(fixturePath)) {
  assert(Date.now() < deadline, "bounded live fixture wait");
  await new Promise((resolve) => setTimeout(resolve, 250));
}
const fixture = JSON.parse(fs.readFileSync(fixturePath, "utf8")), root = path.dirname(fixturePath);
assert.equal(fixture.productLine, "OPTION");
fs.copyFileSync(fixturePath, path.join(root, "trade-fixture-private.json"));
fs.chmodSync(path.join(root, "trade-fixture-private.json"), 0o600);
const parse = (text) => JSON.parse(text, (_key, value, context) => typeof value === "number" && Number.isInteger(value) && !Number.isSafeInteger(value) ? context.source : value);
const headers = { Authorization: `Bearer ${fixture.adminAccessToken}`, "X-Product-Line": "OPTION" };
const me = await fetch("http://127.0.0.1:9094/api/v1/auth/me", { headers });
assert.equal(me.status, 200);
const user = await me.json(); assert(user.roles.includes("SUPER_ADMIN"));
const response = await fetch(`http://127.0.0.1:9094${fixture.tradeQuery.historyPath}`, { headers });
assert.equal(response.status, 200);
const history = parse(await response.text()); assert.equal(history.trades.length, 2);
const { chromium } = await import(process.env.TRADE_QUERY_PLAYWRIGHT_MODULE || "playwright-core");
const browser = await chromium.launch({ headless: true, ...(process.env.TRADE_QUERY_CHROMIUM ? { executablePath: process.env.TRADE_QUERY_CHROMIUM } : {}) });
let page;
const evidence = { productLine: "OPTION", tradeIds: fixture.tradeQuery.tradeIds, pageErrors: [] };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript((session) => localStorage.setItem("surprising-admin.session", JSON.stringify(session)), { accessToken: fixture.adminAccessToken, user });
  page = await context.newPage();
  page.on("pageerror", (error) => evidence.pageErrors.push(String(error)));
  await page.goto("http://127.0.0.1:5173/#orders");
  await page.getByRole("combobox", { name: /^产品线/ }).selectOption("OPTION");
  const userFilter = page.getByLabel("User ID", { exact: true });
  const orderFilter = page.getByLabel("Order / Trigger ID", { exact: true });
  await userFilter.fill(String(fixture.userId));
  await page.getByLabel("币对 ID", { exact: true }).fill(fixture.instrumentId);
  const query = page.getByRole("button", { name: "查询", exact: true });
  const audit = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "成交审计", exact: true }) });
  await query.click();
  for (const id of fixture.tradeQuery.tradeIds) await audit.getByRole("cell", { name: id, exact: true }).waitFor();
  assert.equal(await audit.locator("tbody tr").count(), 2);
  assert.equal(await audit.getByRole("cell", { name: "OPTION", exact: true }).count(), 2);
  for (const id of fixture.tradeQuery.tradeIds) assert.equal(await audit.getByRole("cell", { name: id, exact: true }).getAttribute("title"), id);
  evidence.completeIdTitles = true;
  const makerOrder = String(history.trades[0].makerOrderId); assert(BigInt(makerOrder) > 2n ** 53n);
  await orderFilter.fill(makerOrder);
  const wrongSide = page.waitForResponse((r) => r.url().includes("/trading-orders/trades?") && r.url().includes(`orderId=${makerOrder}`));
  await query.click(); assert.equal((parse(await (await wrongSide).text())).trades.length, 0);
  assert.equal(await audit.locator("tbody tr").count(), 0);
  await userFilter.fill(String(fixture.makerId));
  const rightSide = page.waitForResponse((r) => r.url().includes("/trading-orders/trades?") && r.url().includes(`orderId=${makerOrder}`));
  await query.click(); assert.equal(parse(await (await rightSide).text()).trades.length, 1);
  await audit.getByRole("cell", { name: makerOrder, exact: true }).waitFor();
  evidence.exactInt64OrderFilter = true; evidence.userAndOrderSameSide = true;
  await userFilter.fill(String(fixture.userId)); await orderFilter.fill("");
  await page.getByLabel("Limit", { exact: true }).fill("1");
  await query.click();
  await audit.locator("tbody tr").waitFor();
  const first = await audit.locator("tbody tr td").nth(1).innerText();
  await audit.getByRole("button", { name: "下一页", exact: true }).click();
  await audit.locator("tbody tr").waitFor();
  const second = await audit.locator("tbody tr td").nth(1).innerText();
  assert.notEqual(first, second); assert.deepEqual(new Set([first, second]), new Set(fixture.tradeQuery.tradeIds));
  await page.getByRole("combobox", { name: /^成交排序/ }).selectOption("eventTime.asc");
  await query.click(); await audit.locator("tbody tr").waitFor();
  assert.equal(await audit.locator("tbody tr td").nth(1).innerText(), second);
  evidence.cursorPaging = true; evidence.ascendingAndDescending = true;
  const pattern = "**/api/v1/admin/gateway/trading-orders/trades?**";
  await page.route(pattern, (route) => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "TRADE_READ_VIEW_UNAVAILABLE" }) }));
  await query.click(); await page.getByText(/成交列表：TRADE_READ_VIEW_UNAVAILABLE/).waitFor();
  assert.equal(await audit.locator("tbody tr").count(), 0);
  await page.unroute(pattern); await query.click(); await audit.locator("tbody tr").waitFor();
  evidence.unavailableClearsRows = true;
  await audit.screenshot({ path: path.join(root, "trade-admin-desktop.png") });
  await page.setViewportSize({ width: 360, height: 900 });
  const scrolled = await audit.locator(".table-wrap").evaluate((element) => {
    element.scrollLeft = element.scrollWidth;
    return element.scrollLeft > 0 && element.scrollWidth > element.clientWidth;
  });
  assert(scrolled); assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  evidence.mobileTableScrolls = true; evidence.noBodyOverflow = true;
  await audit.screenshot({ path: path.join(root, "trade-admin-mobile.png") });
  evidence.widths = [1440, 360]; assert.deepEqual(evidence.pageErrors, []);
  fs.writeFileSync(path.join(root, "trade-admin-evidence.json"), JSON.stringify(evidence, null, 2));
  fs.writeFileSync(`${fixturePath}.done`, "PASS\n");
  console.log("TRADE_ADMIN_LIVE_PASS exactInt64=true sameSide=true paging=true sorts=true unavailable=true widths=1440,360");
} catch (error) {
  if (page) await page.screenshot({ path: path.join(root, "trade-admin-failure.png"), fullPage: true });
  throw error;
} finally { await browser.close(); }
